-- ============================================================================
-- PERMISSION CATALOG
-- ============================================================================

create table if not exists public.permissions (
  id bigint generated by default as identity primary key,

  permission_key text not null,
  domain text not null,
  description text not null,

  created_at timestamptz not null default timezone('utc', now()),

  constraint permissions_key_unique
    unique (permission_key),

  constraint permissions_key_format
    check (
      permission_key ~ '^[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*$'
    ),

  constraint permissions_domain_format
    check (
      domain ~ '^[a-z][a-z0-9_]*$'
    ),

  constraint permissions_description_length
    check (
      char_length(trim(description)) between 1 and 500
    )
);

create index if not exists permissions_domain_idx
  on public.permissions(domain);

-- ============================================================================
-- ROLE -> PERMISSION MAPPING
-- ============================================================================

create table if not exists public.role_permissions (
  role_code public.user_role not null,
  permission_id bigint not null,

  created_at timestamptz not null default timezone('utc', now()),

  primary key (role_code, permission_id),

  constraint role_permissions_permission_fk
    foreign key (permission_id)
    references public.permissions(id)
    on delete restrict
);

create index if not exists role_permissions_permission_idx
  on public.role_permissions(permission_id);

