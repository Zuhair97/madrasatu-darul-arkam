-- ============================================================================
-- RLS
-- ============================================================================

alter table public.permissions enable row level security;
alter table public.role_permissions enable row level security;

-- Authenticated users may read the permission catalog.
-- This does not grant access to protected school data.
drop policy if exists "permissions_select_authenticated"
on public.permissions;

create policy "permissions_select_authenticated"
on public.permissions
for select
to authenticated
using (true);

-- Role-permission assignments are not directly writable by application users.
-- The authorization helper below reads them through SECURITY DEFINER.
drop policy if exists "role_permissions_select_authenticated"
on public.role_permissions;

create policy "role_permissions_select_super_admin"
on public.role_permissions
for select
to authenticated
using (
  public.current_user_role() = 'super_admin'::public.user_role
);

-- No INSERT / UPDATE / DELETE policies are intentionally created.
-- Permission assignments are controlled through reviewed migrations/admin
-- workflows, not arbitrary client-side writes.

-- ============================================================================
-- AUTHORIZATION HELPER
-- ============================================================================

create or replace function public.has_permission(
  requested_permission text
)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles profile
    join public.role_permissions rp
      on rp.role_code = profile.role
    join public.permissions permission
      on permission.id = rp.permission_id
    where profile.id = auth.uid()
      and profile.status = 'active'
      and permission.permission_key = requested_permission
  );
$$;

-- Only authenticated application users may call the authorization helper.
revoke all on function public.has_permission(text) from public;

grant execute on function public.has_permission(text)
to authenticated;

comment on table public.permissions is
